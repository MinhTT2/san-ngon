async function signIn(context, flags = {}) {
  const b64 = value => Buffer.from(JSON.stringify(value)).toString('base64url');
  const exp = Math.floor(Date.now() / 1000) + 3600;
  const token = `${b64({ alg: 'HS256', typ: 'JWT' })}.${b64({ sub: owner, exp, aud: 'authenticated', role: 'authenticated', fixture_role: 'owner', ...flags })}.fixture`;
  const value = `base64-${b64({ access_token: token, refresh_token: 'fixture-only', expires_at: exp, expires_in: 3600, token_type: 'bearer', user: { id: owner, email: 'fixture@example.invalid' } })}`;
  await context.addCookies([{ name: 'sb-127-auth-token', value, url: origin, sameSite: 'Lax' }]);
}
async function session(flags) {
  const context = await browser.newContext({ locale: 'vi-VN', timezoneId: 'Asia/Ho_Chi_Minh', viewport: { width: 1440, height: 1000 } });
  await signIn(context, flags);
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/api/**', route => route.request().method() === 'GET' ? route.continue() : json(route, { error: 'Unmocked API write rejected' }, 403));
  await page.route('**/rest/v1/rpc/**', route => ['get_venue_availability'].includes(new URL(route.request().url()).pathname.split('/').at(-1)) ? route.continue() : json(route, { message: 'Unmocked browser RPC rejected' }, 403));
  return { context, page };
}
