import assert from 'node:assert/strict';
import { setTimeout as wait } from 'node:timers/promises';
import { createRefreshQueue } from '../lib/refresh-queue.ts';
let calls = 0;
let editable = false;
const queue = createRefreshQueue(() => calls++, () => !editable, 10);
for (let i = 0; i < 30; i++) queue.request();
await wait(30);
assert.equal(calls, 1, 'A burst of events triggers one refresh');
editable = true;
queue.request(); await wait(30);
assert.equal(calls, 1, 'Editing, hidden/offline pages and dialogs can defer refresh');
editable = false;
queue.flush(); await wait(30);
assert.equal(calls, 2, 'The deferred update resumes when safe');
queue.request(); queue.dispose(); await wait(30);
assert.equal(calls, 2, 'Unmount cancels outstanding refresh');
queue.request(); await wait(30);
assert.equal(calls, 2, 'Disposed pages cannot request more work');
console.log('OK: refresh coalescing, edit deferral/resumption and cleanup.');
