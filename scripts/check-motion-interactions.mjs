// Isolated localhost fixtures only; verifies motion never interferes with input or accessibility.
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';
const origin = process.argv[2];
assert(['localhost', '127.0.0.1'].includes(new URL(origin).hostname));
const output = process.env.UX_SCREENSHOT_DIR;
if (output) await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_EXECUTABLE ? { executablePath: process.env.CHROMIUM_EXECUTABLE } : {}) });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, locale: 'vi-VN' });
const errors = [];
const page = await context.newPage();
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(`${origin}/tim-san`);
  const rail = page.getByRole('navigation', { name: 'Chọn nhanh môn chơi' });
  await rail.getByRole('link', { name: 'Cầu lông', exact: true }).click();
  await page.waitForURL(url => url.searchParams.get('sport') === 'badminton');
  await page.waitForTimeout(600);
  const active = await rail.locator('[aria-current]').boundingBox();
  const marker = await rail.locator('.pf-nav-marker').boundingBox();
  assert(Math.abs(active.x - marker.x) < 2 && Math.abs(active.width - marker.width) < 2, 'Sport selection surface aligns after navigation');
  const card = page.locator('.pf-venue-card').first();
  const cover = await card.locator('.pf-venue-cover').boundingBox();
  const body = await card.locator('.pf-venue-body').boundingBox();
  assert(cover.x + cover.width <= body.x + 1, 'Sparse desktop results use the full horizontal card');
  await page.setViewportSize({ width: 390, height: 900 });
  const mobileCover = await card.locator('.pf-venue-cover').boundingBox();
  const mobileBody = await card.locator('.pf-venue-body').boundingBox();
  assert(mobileCover.y + mobileCover.height <= mobileBody.y + 1, 'Mobile results keep the image above readable details');

  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(`${origin}/san/san-cau-giay`);
  const trigger = page.getByRole('button', { name: 'Mở ảnh 1 của Sân Cầu Giấy', exact: true });
  await trigger.click();
  const viewer = page.getByRole('dialog', { name: 'Ảnh Sân Cầu Giấy', exact: true });
  const image = viewer.locator('[data-gallery-stage] img');
  await page.waitForFunction(() => document.querySelector('[data-gallery-stage] img')?.classList.contains('invisible') === false);
  await viewer.getByRole('button', { name: 'Phóng to', exact: true }).click();
  assert.match(await image.getAttribute('style'), /scale\(1.5\)/, 'Entrance animation preserves the zoom transform');
  await page.keyboard.press('ArrowRight');
  await page.waitForFunction(() => document.querySelector('[data-gallery-stage] img')?.alt.endsWith('ảnh 2') && !document.querySelector('[data-gallery-stage] img')?.classList.contains('invisible'));
  await page.waitForTimeout(400);
  assert.match(await image.getAttribute('style'), /scale\(1\)/);
  assert.equal(await image.evaluate(element => getComputedStyle(element).opacity), '1');
  await page.keyboard.press('Escape');
  await viewer.waitFor({ state: 'detached' });
  assert(await trigger.evaluate(element => element === document.activeElement), 'Gallery restores keyboard focus');
  const slot = page.getByRole('button', { name: /^10:00, còn sân/ });
  await slot.click();
  const summary = page.getByRole('complementary', { name: 'Tóm tắt đặt sân' });
  await summary.getByRole('button', { name: 'Tiếp tục đặt sân', exact: true }).waitFor();
  await page.waitForTimeout(600);
  assert.equal(await slot.getAttribute('aria-pressed'), 'true');
  if (output) {
    await page.evaluate(() => scrollTo(0, 0));
    await page.screenshot({ path: `${output}/review-venue-1440.png`, fullPage: true });
  }

  const id = 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa';
  const exp = Math.floor(Date.now() / 1000) + 3600;
  const b64 = value => Buffer.from(JSON.stringify(value)).toString('base64url');
  const token = `${b64({ alg: 'HS256', typ: 'JWT' })}.${b64({ sub: id, exp, aud: 'authenticated', role: 'authenticated', fixture_role: 'admin' })}.fixture`;
  await context.addCookies([{ name: 'sb-127-auth-token', url: origin, sameSite: 'Lax', value: `base64-${b64({ access_token: token, refresh_token: 'fixture-only', expires_at: exp, expires_in: 3600, token_type: 'bearer', user: { id, email: 'fixture@example.invalid' } })}` }]);
  await page.goto(`${origin}/admin/users`);
  const create = page.getByRole('button', { name: 'Tạo tài khoản', exact: true });
  await create.click();
  const dialog = page.getByRole('dialog', { name: 'Tạo tài khoản', exact: true });
  const panel = dialog.locator('[data-modal-panel]');
  assert(await panel.evaluate(element => element.getAnimations().some(animation => animation.playState === 'running')), 'Dialog has a native entrance effect');
  await dialog.getByLabel('Họ tên', { exact: true }).fill('Minh kiểm tra chuyển động');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.waitForTimeout(60);
  assert.equal(await panel.evaluate(element => element.getAnimations().length), 0, 'Changing reduced motion immediately cancels the library effect');
  assert.equal(await panel.evaluate(element => element.style.transform), '', 'Cancelled motion leaves no containing-block transform');
  assert.equal(await dialog.getByLabel('Họ tên', { exact: true }).inputValue(), 'Minh kiểm tra chuyển động');
  assert(await dialog.getByLabel('Họ tên', { exact: true }).evaluate(element => element === document.activeElement));
  await page.keyboard.press('Escape');
  assert(await create.evaluate(element => element === document.activeElement));
  await create.click();
  assert.equal(await panel.evaluate(element => element.getAnimations().length), 0, 'Reduced-motion dialogs remain immediately usable');
  await page.keyboard.press('Escape');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await create.click();
  await page.waitForTimeout(600);
  assert.equal(await panel.evaluate(element => element.style.transform), '', 'Completed effect restores natural layout');
  if (output) await page.screenshot({ path: `${output}/review-dialog-1440.png`, fullPage: true });
  await page.keyboard.press('Escape');
  assert.deepEqual(errors, []);
  console.log('OK: selection alignment, adaptive cards, gallery zoom/focus, booking selection and motion preference changes.');
} finally { await context.close(); await browser.close(); }
